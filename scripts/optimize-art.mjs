import sharp from "sharp";
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
const dir = "public/illustrations";
const review = JSON.parse(await readFile("artwork/review.json", "utf8"));
const inputs = new Map();
for (const folder of ["artwork/originals", dir]) {
  const files = await readdir(folder).catch(() => []);
  for (const file of files.filter((f) => f.endsWith(".png")))
    inputs.set(file.slice(0, -4), `${folder}/${file}`);
}
const ids = (await readdir(dir))
  .filter((f) => f.endsWith(".svg") && !f.endsWith("-diagram.svg"))
  .map((f) => f.slice(0, -4))
  .sort();
const existingFiles = new Set(await readdir(dir));
const map = {};
const report = [];
for (const id of ids) {
  const sourceId = review.overrides[id] ?? id;
  const source = inputs.get(sourceId);
  const servedFile = id.startsWith("question-")
    ? `${id}-diagram.svg`
    : `${sourceId}.webp`;
  if (
    (source || existingFiles.has(servedFile)) &&
    !review.fallbackOnly.includes(id)
  ) {
    if (source && !id.startsWith("question-"))
      await sharp(source)
        .resize(768, 768, { fit: "inside", withoutEnlargement: true })
        .webp({ quality: 85 })
        .toFile(`${dir}/${sourceId}.webp`);
    map[id] = id.startsWith("question-")
      ? `illustrations/${id}-diagram.svg`
      : `illustrations/${sourceId}.webp`;
    report.push(
      `| ${id} | generated | ${id.startsWith("question-") ? id + "-diagram.svg" : sourceId + ".webp"} | ${id}.svg |`,
    );
  } else
    report.push(
      `| ${id} | fallback; AI artwork pending | ${id}.svg | ${id}.svg |`,
    );
}
await writeFile(
  "src/data/generatedAssets.ts",
  `// Generated by scripts/optimize-art.mjs; selections are in artwork/review.json.\nexport const generatedAssets: Record<string,string> = ${JSON.stringify(map, null, 2)};\n`,
);
await mkdir("docs", { recursive: true });
await writeFile(
  "docs/asset-report.md",
  `# Artwork report\n\n${Object.keys(map).length} of ${ids.length} assets use AI-generated artwork from the built-in imagegen tool: one hero, eight question images and 38 haircut portraits in the complete set. All ${ids.length} assets have deterministic local SVG fallbacks. Portrait artwork is optimized to 768px WebP. The eight served question illustrations are labelled, self-contained SVG comparison diagrams composed from generated portraits. Raw AI-generated question montages were not selected because their ordering and cut distinctions were unclear. PNG originals are retained locally under artwork/originals (excluded from git and the production bundle). No runtime generation or third-party requests.\n\n## Review\n\n${review.notes.join("\n\n")}\n\nThe textured-crop original was the identity reference for subsequent portraits. The hero was generated separately using the shared character description. Prompts are in illustration-prompts.md; reference-image calls additionally instructed exact preservation of face, pose, shirt and rendering style.\n\n| Asset ID | Status | Served file | Fallback |\n| --- | --- | --- | --- |\n${report.join("\n")}\n`,
);
console.log(`Optimized ${Object.keys(map).length}/${ids.length} assets.`);
